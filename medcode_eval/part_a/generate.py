"""Generate the Part A probes: does a model know the ICD-10-CM FY2027 code set?

Three probe types, all built from refdata files only:

  code_to_description  a billable code and 4 long descriptions (A-D), one of
                       them its own; the answer is the letter.
  description_to_code  a billable code's long description; the answer is the
                       code. Codes whose long description is shared with
                       another billable code are left out.
  status               a string shown as a code; the answer is billable,
                       header or not_a_code. not_a_code probes have a kind:
                       deleted, substituted, extended, placeholder_prefix.

Sampling gives each chapter the same number of probes within each type,
within each status answer and within each generated not_a_code kind
(allocate()). Deleted-code probes are outside that balance.

Codes are shown with the dot after the third character; answers store the
code without it. One fixed seed (SEED) and the same Python version give
byte-identical output files. No timestamps are written.

Usage (from the repo root):
    venv/bin/python -m medcode_eval.part_a.generate [--out data/part_a]
"""

import argparse
import hashlib
import json
import platform
import random
from collections import Counter, defaultdict
from pathlib import Path

from medcode_eval import addenda, orderfile, tabular

SEED = 20261001
CODE_SET = "ICD-10-CM FY2027 (October 1, 2026 release)"
# every probe records its origin (CLAUDE.md: test items record their origin)
ORIGIN = "generated by medcode_eval/part_a/generate.py from refdata; no human or model input"
REPO_ROOT = Path(__file__).resolve().parents[2]
REFDATA = Path("refdata") / "icd10cm_fy2027"
DEFAULT_PATHS = {
    "order": REFDATA / "icd10cm_order_2027.txt",
    "addenda": REFDATA / "icd10cm_order_addenda_2027.txt",
    "tabular": REFDATA / "icd10cm_tabular_2027.xml",
}
DEFAULT_OUT = Path("data") / "part_a"

TYPES = ("code_to_description", "description_to_code", "status")
FULL_SIZES = {"code_to_description": 500, "description_to_code": 500, "status": 501}
LITE_SIZES = {"code_to_description": 50, "description_to_code": 50, "status": 51}
STATUS_ANSWERS = ("billable", "header", "not_a_code")
KINDS = ("deleted", "substituted", "extended", "placeholder_prefix")
GENERATED_KINDS = KINDS[1:]
LETTERS = "ABCD"
ID_PREFIX = {"code_to_description": "c2d", "description_to_code": "d2c", "status": "st"}


def display(code):
    """Show a code with the dot after the third character."""
    return code if len(code) <= 3 else f"{code[:3]}.{code[3:]}"


def allocate(total, caps):
    """Spread `total` over chapters as equally as their capacities allow.

    caps: list of (chapter, capacity) in chapter order. Every chapter gets
    the same share; a chapter with too few takes all it has and the
    shortfall is spread over the others; a remainder goes one each to the
    first chapters in chapter order. Returns {chapter: count}.
    """
    cap = dict(caps)
    if total > sum(cap.values()):
        raise ValueError(f"cannot place {total} probes in capacity {sum(cap.values())}")
    out = {k: 0 for k, _ in caps}
    active = [k for k, _ in caps if cap[k] > 0]
    remaining = total
    while active:
        share, extra = divmod(remaining, len(active))
        small = [k for k in active if cap[k] <= share]
        if not small:
            for i, k in enumerate(active):
                out[k] = share + (1 if i < extra else 0)
            break
        for k in small:
            out[k] = cap[k]
            remaining -= cap[k]
        active = [k for k in active if k not in small]
    return out


def equal_shares(total, keys):
    """Split total over keys equally; the remainder goes to the first keys."""
    base, extra = divmod(total, len(keys))
    return {k: base + (1 if i < extra else 0) for i, k in enumerate(keys)}


class CodeSet:
    """The refdata facts the generator needs, read once."""

    def __init__(self, records, chapters, deleted, sources):
        self.records = records
        self.by_code = {r.code: r for r in records}
        self.chapter_list = chapters
        self.categories = [r.code for r in records if len(r.code) == 3]
        self.cat_index = {c: i for i, c in enumerate(self.categories)}
        self.chapter = {c: tabular.chapter_of(c, chapters) for c in self.categories}
        missing = [c for c, n in self.chapter.items() if n is None]
        if missing:
            raise ValueError(f"categories in no chapter: {missing}")
        self.chapters = sorted(set(self.chapter.values()))
        self.billable_by_cat = defaultdict(list)
        for r in records:
            if r.billable:
                self.billable_by_cat[r.code[:3]].append(r)
        self.parents = orderfile.parent_map(records)
        self.deleted = deleted
        self.sources = sources

    def chapter_of_code(self, code):
        cat = code[:3]
        if cat in self.chapter:
            return self.chapter[cat]
        return tabular.chapter_of(cat, self.chapter_list)

    def by_chapter(self, items, code_of=lambda x: x.code):
        groups = {ch: [] for ch in self.chapters}
        for item in items:
            groups[self.chapter_of_code(code_of(item))].append(item)
        return groups

    def distractors(self, code, rng):
        """Three long descriptions of other billable codes, all different.

        From the code's own category; where it has fewer than 3 others,
        filled from the nearest categories in file order (at each distance
        the earlier category first).
        """
        answer = self.by_code[code].long
        cat = code[:3]

        def texts(category, taken):
            out = []
            for r in self.billable_by_cat[category]:
                if r.code != code and r.long != answer and r.long not in taken \
                        and r.long not in out:
                    out.append(r.long)
            return out

        picked = []
        own = texts(cat, picked)
        if len(own) >= 3:
            return rng.sample(own, 3)
        picked.extend(own)
        i = self.cat_index[cat]
        for d in range(1, len(self.categories)):
            for j in (i - d, i + d):
                if not 0 <= j < len(self.categories):
                    continue
                cand = texts(self.categories[j], picked)
                need = 3 - len(picked)
                picked.extend(cand if len(cand) <= need else rng.sample(cand, need))
                if len(picked) == 3:
                    return picked
        raise ValueError(f"not enough distractors for {code}")


def load_codeset(paths=None, root=REPO_ROOT):
    """Read the order, addenda and tabular files named in paths."""
    root = Path(root)
    paths = {k: root / v for k, v in (paths or DEFAULT_PATHS).items()}
    records = orderfile.load(paths["order"])
    codes = {r.code for r in records}
    deleted = []
    for r in addenda.load(paths["addenda"]).records:
        if r.action == "delete" and r.code not in codes and r.code not in deleted:
            deleted.append(r.code)
    chapters = tabular.load_chapters(paths["tabular"])
    sources = {k: p.resolve().relative_to(root.resolve()).as_posix()
               for k, p in paths.items()}
    return CodeSet(records, chapters, deleted, sources)


def _base(cs, type_, chapter, source="order"):
    return {"type": type_, "chapter": chapter, "source": cs.sources[source],
            "code_set": CODE_SET, "origin": ORIGIN}


def _sample_by_chapter(cs, total, pool, rng, code_of=lambda x: x.code):
    groups = cs.by_chapter(pool, code_of)
    counts = allocate(total, [(ch, len(groups[ch])) for ch in cs.chapters])
    chosen = []
    for ch in cs.chapters:
        chosen.extend(rng.sample(groups[ch], counts[ch]))
    return chosen


def _shared_descriptions(records):
    counts = Counter(r.long for r in records if r.billable)
    return {d for d, n in counts.items() if n > 1}


def _position_chars(records):
    """Characters seen at each (code length, position) in the order file."""
    seen = defaultdict(set)
    for r in records:
        for i, ch in enumerate(r.code):
            seen[(len(r.code), i)].add(ch)
    return {k: sorted(v) for k, v in seen.items()}


def _generated_candidates(cs):
    """Per kind, per chapter: list of (source code, sorted variant strings)."""
    codes = set(cs.by_code)
    deleted = set(cs.deleted)
    chars = _position_chars(cs.records)
    billable = [r for r in cs.records if r.billable]
    out = {k: {ch: [] for ch in cs.chapters} for k in GENERATED_KINDS}

    def ok(s):
        return s not in codes and s not in deleted

    for r in billable:
        c, n = r.code, len(r.code)
        ch = cs.chapter_of_code(c)
        subs = [c[:-1] + x for x in chars.get((n, n - 1), []) if x != c[-1]]
        subs = [s for s in subs if ok(s)]
        if subs:
            out["substituted"][ch].append((c, subs))
        if n < 7:
            ext = [c + x for x in chars.get((n + 1, n), [])]
            ext = [s for s in ext if ok(s)]
            if ext:
                out["extended"][ch].append((c, ext))
    seen = set()
    for r in cs.records:
        c = r.code
        if len(c) > 3 and cs.parents[c] != c[:-1]:
            s = c[:-1]
            if s not in seen and ok(s):
                seen.add(s)
                out["placeholder_prefix"][cs.chapter_of_code(c)].append((c, [s]))
    return out


def _status_probes(cs, total, rng):
    if total % 3:
        raise ValueError("status size must be a multiple of 3")
    quota = total // 3
    probes = []
    billable = [r for r in cs.records if r.billable]
    headers = [r for r in cs.records if not r.billable]
    for answer, pool in (("billable", billable), ("header", headers)):
        for r in _sample_by_chapter(cs, quota, pool, rng):
            p = _base(cs, "status", cs.chapter_of_code(r.code))
            p.update(code=display(r.code), answer=answer)
            probes.append(p)

    n_deleted = min(len(cs.deleted), quota // 2)
    deleted = (list(cs.deleted) if n_deleted == len(cs.deleted)
               else sorted(rng.sample(cs.deleted, n_deleted), key=cs.deleted.index))
    for code in deleted:
        p = _base(cs, "status", cs.chapter_of_code(code), "addenda")
        p.update(code=display(code), answer="not_a_code", kind="deleted")
        probes.append(p)

    used = set()
    cands = _generated_candidates(cs)
    shares = equal_shares(quota - n_deleted, GENERATED_KINDS)
    for kind in GENERATED_KINDS:
        groups = cands[kind]
        counts = allocate(shares[kind], [(ch, len(groups[ch])) for ch in cs.chapters])
        for ch in cs.chapters:
            order = list(groups[ch])
            rng.shuffle(order)
            made = 0
            for src, variants in order:
                if made == counts[ch]:
                    break
                free = [v for v in variants if v not in used]
                if not free:
                    continue
                s = rng.choice(free)
                used.add(s)
                p = _base(cs, "status", ch)
                p.update(code=display(s), answer="not_a_code", kind=kind,
                         derived_from=src)
                probes.append(p)
                made += 1
            if made < counts[ch]:
                raise ValueError(f"chapter {ch}: too few unique {kind} strings")
    return probes


def build_full(cs, sizes, rng):
    """Build the full probe set; returns probes in file order."""
    by_type = {}

    c2d = []
    pool = [r for r in cs.records if r.billable]
    for r in _sample_by_chapter(cs, sizes["code_to_description"], pool, rng):
        options = cs.distractors(r.code, rng)
        rng.shuffle(options)
        pos = rng.randrange(4)
        options.insert(pos, r.long)
        p = _base(cs, "code_to_description", cs.chapter_of_code(r.code))
        p.update(code=display(r.code), options=options, answer=LETTERS[pos])
        c2d.append(p)
    by_type["code_to_description"] = c2d

    shared = _shared_descriptions(cs.records)
    pool = [r for r in cs.records if r.billable and r.long not in shared]
    d2c = []
    for r in _sample_by_chapter(cs, sizes["description_to_code"], pool, rng):
        p = _base(cs, "description_to_code", cs.chapter_of_code(r.code))
        p.update(description=r.long, answer=r.code)
        d2c.append(p)
    by_type["description_to_code"] = d2c

    by_type["status"] = _status_probes(cs, sizes["status"], rng)

    probes = []
    for t in TYPES:
        items = by_type[t]
        rng.shuffle(items)
        for i, p in enumerate(items, start=1):
            probes.append({"id": f"{ID_PREFIX[t]}-{i:04d}", **p})
    _check_not_a_code(cs, probes)
    return probes


def _check_not_a_code(cs, probes):
    codes, deleted = set(cs.by_code), set(cs.deleted)
    strings = [p["code"].replace(".", "") for p in probes
               if p.get("answer") == "not_a_code"]
    if len(strings) != len(set(strings)):
        raise ValueError("a not_a_code string is repeated")
    for p in probes:
        if p.get("answer") != "not_a_code":
            continue
        s = p["code"].replace(".", "")
        if s in codes:
            raise ValueError(f"not_a_code string {s} is in the order file")
        if p["kind"] != "deleted" and s in deleted:
            raise ValueError(f"generated not_a_code string {s} is a deleted code")


def build_lite(full, sizes, rng):
    """Draw the lite set from the full set (same ids, same records)."""
    chapters = sorted({p["chapter"] for p in full if p["chapter"] is not None})

    def pick(items, total):
        groups = {ch: [p for p in items if p["chapter"] == ch] for ch in chapters}
        counts = allocate(total, [(ch, len(groups[ch])) for ch in chapters])
        out = []
        for ch in chapters:
            out.extend(rng.sample(groups[ch], counts[ch]))
        return out

    chosen = []
    for t in ("code_to_description", "description_to_code"):
        chosen += pick([p for p in full if p["type"] == t], sizes[t])
    status = [p for p in full if p["type"] == "status"]
    if sizes["status"] % 3:
        raise ValueError("status size must be a multiple of 3")
    quota = sizes["status"] // 3
    for answer in ("billable", "header"):
        chosen += pick([p for p in status if p["answer"] == answer], quota)
    deleted = [p for p in status if p.get("kind") == "deleted"]
    n_deleted = min(len(deleted), quota // 2)
    chosen += rng.sample(deleted, n_deleted)
    shares = equal_shares(quota - n_deleted, GENERATED_KINDS)
    for kind in GENERATED_KINDS:
        chosen += pick([p for p in status if p.get("kind") == kind], shares[kind])
    full_kinds = {p["kind"] for p in full if "kind" in p}
    lite_kinds = {p["kind"] for p in chosen if "kind" in p}
    if full_kinds - lite_kinds:
        raise ValueError(f"lite lacks kinds {sorted(full_kinds - lite_kinds)}")
    ids = {p["id"] for p in chosen}
    return [p for p in full if p["id"] in ids]


def counts(probes):
    """Counts by type, chapter, status answer and not_a_code kind."""

    def key(ch):
        return "none" if ch is None else str(ch)

    def nested(items, outer):
        out = defaultdict(Counter)
        for p in items:
            out[outer(p)][key(p["chapter"])] += 1
        return {k: dict(v) for k, v in out.items()}

    status = [p for p in probes if p["type"] == "status"]
    nac = [p for p in status if p["answer"] == "not_a_code"]
    return {
        "total": len(probes),
        "by_type": dict(Counter(p["type"] for p in probes)),
        "by_type_chapter": nested(probes, lambda p: p["type"]),
        "status_by_answer": dict(Counter(p["answer"] for p in status)),
        "status_by_answer_chapter": nested(status, lambda p: p["answer"]),
        "not_a_code_by_kind": dict(Counter(p["kind"] for p in nac)),
        "not_a_code_by_kind_chapter": nested(nac, lambda p: p["kind"]),
    }


def _jsonl(probes):
    return "".join(json.dumps(p, sort_keys=True) + "\n" for p in probes).encode("ascii")


def _sha(data):
    return hashlib.sha256(data).hexdigest()


def generate(out_dir=None, paths=None, root=REPO_ROOT, seed=SEED,
             full_sizes=FULL_SIZES, lite_sizes=LITE_SIZES):
    """Write probes_full.jsonl, probes_lite.jsonl and manifest.json."""
    root = Path(root)
    out = Path(out_dir) if out_dir is not None else root / DEFAULT_OUT
    cs = load_codeset(paths, root)
    rng = random.Random(seed)
    full = build_full(cs, full_sizes, rng)
    lite = build_lite(full, lite_sizes, rng)
    files = {"probes_full.jsonl": _jsonl(full), "probes_lite.jsonl": _jsonl(lite)}
    refdata_sha = {}
    for role in ("order", "addenda", "tabular"):
        refdata_sha[cs.sources[role]] = _sha((root / (paths or DEFAULT_PATHS)[role]).read_bytes())
    manifest = {
        "code_set": CODE_SET,
        "seed": seed,
        "python_version": platform.python_version(),
        "generator": "medcode_eval/part_a/generate.py",
        "sizes": {"full": dict(full_sizes), "lite": dict(lite_sizes)},
        "refdata_sha256": refdata_sha,
        "outputs_sha256": {k: _sha(v) for k, v in files.items()},
        "counts": {"full": counts(full), "lite": counts(lite)},
    }
    out.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (out / name).write_bytes(data)
    (out / "manifest.json").write_bytes(
        (json.dumps(manifest, sort_keys=True, indent=2) + "\n").encode("ascii"))
    return manifest


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", help="output directory (default data/part_a)")
    args = ap.parse_args(argv)
    m = generate(args.out)
    for name, sha in m["outputs_sha256"].items():
        print(f"{sha}  {name}")


if __name__ == "__main__":
    main()
